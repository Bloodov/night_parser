"""
Определение языка чата (а не просто алфавита) — по названию + описанию.

В отличие от services/translit.py (который различает только АЛФАВИТ —
кириллица/латиница), этот модуль пытается определить именно ЯЗЫК: отличить
русский от украинского (оба кириллица), английский от немецкого/испанского
(оба латиница) и т.д.

ВАЖНАЯ ОГОВОРКА: определение языка на коротком тексте (а название чата —
это обычно 2-5 слов) статистически ненадёжно. Проверено на практике: одно
слово "Python" библиотека определила как валлийский, "Крипто Трейдинг" (без
описания) — как болгарский вместо русского. Поэтому:
  1. Для определения используется НАЗВАНИЕ + ОПИСАНИЕ вместе (больше текста —
     точнее результат), а не одно название.
  2. Слишком короткий/неоднозначный текст даёт None, а не случайное значение —
     лучше честно не знать язык, чем угадать неправильно.
  3. Сортировка результатов поиска (см. database.py) использует определение
     языка как ПЕРВИЧНЫЙ критерий, но с откатом на алфавит (services/translit)
     как вторичный — если язык не определился или определился ошибочно, чат
     всё равно попадёт в разумную группу по алфавиту, а не в конец списка.
"""

import logging

from langdetect import detect, DetectorFactory, LangDetectException

# langdetect по умолчанию НЕ детерминирован (использует вероятностную выборку) —
# без фиксации seed один и тот же текст может дать разные языки при разных
# запусках. Фиксируем один раз при импорте модуля.
DetectorFactory.seed = 0

logger = logging.getLogger(__name__)

MIN_TEXT_LENGTH = 8  # короче — детектор слишком часто ошибается, не пытаемся


def detect_language(*texts: str) -> str | None:
    """Определяет язык по объединённому тексту (например, название + описание).
    Возвращает ISO 639-1 код ('ru', 'en', 'de', 'uk', ...) или None, если текст
    слишком короткий/неоднозначный для надёжного определения."""
    combined = " ".join(t for t in texts if t).strip()
    if len(combined) < MIN_TEXT_LENGTH:
        return None
    try:
        return detect(combined)
    except LangDetectException:
        return None
